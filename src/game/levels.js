// 每关敌方坦克构成（共 20 辆），难度递增
const STAGE_COMPOSITION = [
  { basic: 16, fast: 4, power: 0, armor: 0 },
  { basic: 14, fast: 4, power: 2, armor: 0 },
  { basic: 12, fast: 4, power: 4, armor: 0 },
  { basic: 10, fast: 4, power: 4, armor: 2 },
  { basic: 8, fast: 6, power: 4, armor: 2 },
  { basic: 6, fast: 6, power: 6, armor: 2 },
  { basic: 4, fast: 6, power: 6, armor: 4 },
  { basic: 2, fast: 6, power: 6, armor: 6 },
  { basic: 2, fast: 4, power: 8, armor: 6 },
  { basic: 0, fast: 4, power: 8, armor: 8 },
];

// 携带道具的闪光红坦在出击序列中的位置（第 4/12/18 辆，仿原版）
const POWERUP_POSITIONS = [3, 11, 17];

// 构建一关的出击队列：各类型交错出现
export function buildSpawnQueue(stageIndex) {
  const comp = STAGE_COMPOSITION[Math.min(stageIndex, STAGE_COMPOSITION.length - 1)];
  const pool = [];
  for (const [type, n] of Object.entries(comp)) {
    for (let i = 0; i < n; i++) pool.push(type);
  }
  // 交错排序：避免同类型扎堆
  const queue = [];
  const buckets = {};
  for (const t of pool) (buckets[t] = buckets[t] || []).push(t);
  let added = true;
  while (added) {
    added = false;
    for (const key of ['basic', 'fast', 'power', 'armor']) {
      if (buckets[key] && buckets[key].length) {
        queue.push(buckets[key].pop());
        added = true;
      }
    }
  }
  return queue.map((type, i) => ({
    type,
    hasPowerup: POWERUP_POSITIONS.includes(i),
  }));
}
